-- 1. TABLA DE PUBLICACIONES (DEVOCIONALES, NOTICIAS, EVENTOS)
create table if not exists public.posts (
    id bigint generated by default as identity primary key,
    title text not null,
    category text not null check (category in ('Devocional', 'Noticia', 'Evento')),
    verse text,
    content text not null,
    author text default 'Dirección Manantial 90.7 FM',
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 2. TABLA DE CONFIGURACIÓN Y AVISOS DE LA EMISORA
create table if not exists public.site_settings (
    key text primary key,
    value text not null,
    updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- ==============================================================================
-- SEGURIDAD: ROW LEVEL SECURITY (RLS)
-- ==============================================================================
alter table public.posts enable row level security;
alter table public.site_settings enable row level security;

-- POLÍTICAS: CUALQUIER OYENTE PUEDE LEER (PÚBLICO)
drop policy if exists "Lectura publica de posts" on public.posts;
create policy "Lectura publica de posts"
    on public.posts for select
    using (true);

drop policy if exists "Lectura publica de configuracion" on public.site_settings;
create policy "Lectura publica de configuracion"
    on public.site_settings for select
    using (true);

-- POLÍTICAS: SOLO EL DIRECTOR AUTENTICADO PUEDE INSERTAR / EDITAR / ELIMINAR
drop policy if exists "Gestion de posts para directores" on public.posts;
create policy "Gestion de posts para directores"
    on public.posts for all
    to authenticated
    using (true)
    with check (true);

drop policy if exists "Gestion de configuracion para directores" on public.site_settings;
create policy "Gestion de configuracion para directores"
    on public.site_settings for all
    to authenticated
    using (true)
    with check (true);

