-- Habilitar extensión para UUIDs si no está habilitada
create extension if not exists "uuid-ossp";

-- ==============================================================================
-- 1. TABLA MAESTRA: CATEGORÍAS (Catálogo normalizado)
-- ==============================================================================
create table if not exists public.categories (
    id smallint generated by default as identity primary key,
    name text not null unique,
    slug text not null unique,
    badge_color text not null default 'amber',
    description text,
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- ==============================================================================
-- 2. TABLA MAESTRA: PERFILES DE AUTORES / LOCUTORES (Vinculado a auth.users)
-- ==============================================================================
create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text not null,
    role text not null default 'Locutor' check (role in ('Director', 'Pastor', 'Locutor', 'Administrador')),
    bio text,
    avatar_url text,
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- ==============================================================================
-- 3. TABLA TRANSACCIONAL: PUBLICACIONES (DEVOCIONALES / NOTICIAS / EVENTOS)
-- ==============================================================================
create table if not exists public.posts (
    id bigint generated by default as identity primary key,
    title text not null,
    category_id smallint not null references public.categories(id) on delete restrict,
    author_id uuid references public.profiles(id) on delete set null,
    verse text,
    content text not null,
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- Índices para optimizar búsquedas por fecha y categoría
create index if not exists idx_posts_category on public.posts(category_id);
create index if not exists idx_posts_created_at on public.posts(created_at desc);

-- ==============================================================================
-- 4. TABLA DE CONFIGURACIÓN Y AVISOS DE CABINA (Key-Value)
-- ==============================================================================
create table if not exists public.site_settings (
    key text primary key,
    value text not null,
    updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- ==============================================================================
-- TRIGGER AUTOMÁTICO: Crear perfil al registrar usuario en Supabase Auth
-- ==============================================================================
create or replace function public.handle_new_user()
returns trigger as $$
begin
    insert into public.profiles (id, full_name, role)
    values (
        new.id,
        coalesce(new.raw_user_meta_data->>'full_name', 'Dirección Manantial 90.7 FM'),
        coalesce(new.raw_user_meta_data->>'role', 'Director')
    )
    on conflict (id) do nothing;
    return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute procedure public.handle_new_user();

