create policy "Lectura publica de categorias" on public.categories for select using (true);

drop policy if exists "Lectura publica de perfiles" on public.profiles;
create policy "Lectura publica de perfiles" on public.profiles for select using (true);

drop policy if exists "Lectura publica de posts" on public.posts;
create policy "Lectura publica de posts" on public.posts for select using (true);

drop policy if exists "Lectura publica de configuracion" on public.site_settings;
create policy "Lectura publica de configuracion" on public.site_settings for select using (true);

-- POLÍTICAS DE ESCRITURA (Solo usuarios autenticados / Director)
drop policy if exists "Gestion de categorias para directores" on public.categories;
create policy "Gestion de categorias para directores"
    on public.categories for all to authenticated using (true) with check (true);

drop policy if exists "Gestion de perfiles propios" on public.profiles;
create policy "Gestion de perfiles propios"
    on public.profiles for all to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Gestion de posts para directores" on public.posts;
create policy "Gestion de posts para directores"
    on public.posts for all to authenticated using (true) with check (true);

drop policy if exists "Gestion de configuracion para directores" on public.site_settings;
create policy "Gestion de configuracion para directores"
    on public.site_settings for all to authenticated using (true) with check (true);

